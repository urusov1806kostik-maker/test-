	local spawn = Instance.new("SpawnLocation")
	spawn.Name = "VoidSpawn"
	spawn.Anchored = true
	spawn.Size = V(8, 1, 8)
	spawn.CFrame = CF(10, GY + 0.5, 10)
	spawn.Color = Color3.fromRGB(70, 40, 110)
	spawn.Material = Enum.Material.Slate
	spawn.Neutral = true
	spawn.Duration = 0
	spawn.TopSurface = Enum.SurfaceType.Smooth
	spawn.Parent = map
