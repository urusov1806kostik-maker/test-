def _n(s):
    return int(s) if s.isdigit() else NUM.get(s, 50)


def normalize(text: str) -> str:
    t = text.lower().replace("ё", "е").strip()
    t = re.sub(r"[.,!?«»\"]+", " ", t)
    t = re.sub(r"^(?:пожалуйста|слушай|эй|ну|давай)\s+", "", t)
    t = re.sub(r"\s+пожалуйста$", "", t)
    t = re.sub(r"^давай\s+", "", t)
    return re.sub(r"\s+", " ", t).strip()


def parse(text: str):
    t = normalize(text)
    # "давай запустим кс" -> "запусти кс"
    t = re.sub(r"^(?:запустим|включим)\s", "запусти ", t)
    t = re.sub(r"^(?:откроем)\s", "открой ", t)
    for pat, fn in RULES:
        m = re.match(pat, t.replace("ё", "е"))
        if m:
            return fn(m)
    return None


SMALLTALK = {
    r"^(?:привет|здравствуй|хай|салют)": "Привет! Сейчас я без связи с ИИ, но простые команды выполню.",
    r"^(?:как дела|как ты)": "Работаю локально, связи с облаком нет, но я на месте.",
    r"^(?:который час|сколько времени)": None,
    r"^(?:спасибо)": "Всегда пожалуйста!",
}


def offline_reply(text: str):
    import time
    t = normalize(text)
    for pat, ans in SMALLTALK.items():
        if re.match(pat, t):
            return ans or time.strftime("Сейчас %H:%M")
    if "систем" in t or "нагрузк" in t:
        return sysmon.summary()
    return ("Нет подключения к Claude API (интернет или ключ). Я могу запускать программы и игры, "
            "управлять громкостью, музыкой, окнами, делать скриншоты и открывать папки.")
